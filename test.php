<h3 style="text-align: center; color: #2c3e50;">رادیو سیمرغ با "شب‌های تهران" به خانه‌های شما می‌آید:</h3>

<h4 style="text-align: center; color: #e67e22;">سریالی صوتی که خاطرات را زنده می‌کند</h4>

<p style="text-align: right; color: #7f8c8d;"><em>تهران، اردیبهشت ۱۴۰۵</em></p>

<p style="text-align: justify;">پس از موفقیت چشمگیر و خاطره‌ساز برنامه "کافه مه آلود" در سال ۱۴۰۴، گروه تولید رادیو
    سیمرغ به تهیه کنندگی سجاد نادر، این بار با پروژه‌ای هیجان‌انگیزتر بازگشته است:</p>

<h4 style="text-align: center; color: #c0392b;"><strong>سریال صوتی "شب‌های تهران"</strong></h4>

<p style="text-align: justify;">این اثر که وعده آن را از ابتدای سال ۱۴۰۵ داده بودیم، هم‌اکنون در مراحل تولید و پخش قرار
    دارد و قرار است هر پنجشنبه شب، میهمان گوش‌های شما از طریق رادیو سیمرغ و پلتفرم‌های محبوب <strong>طاقچه</strong> و
    <strong>فیدیبو</strong> باشد.</p>

<p style="text-align: justify;">"شب‌های تهران" تنها یک سریال صوتی نیست؛ بلکه سفری است به دل شب‌های پایتخت، روایتی از
    قصه‌ها، خاطرات و حال و هوایی که در تاریکی شهر رقم می‌خورد. سجاد نادر، تهیه‌کننده و برنامه‌ساز این اثر، با بهره‌گیری
    از تیمی متشکل از گویندگان و هنرمندان برجسته، تلاش کرده تا تجربه‌ای شنیداری منحصربه‌فرد را برای مخاطبان خلق کند.</p>

<p style="text-align: justify;">این سریال صوتی قصد دارد با داستانی گیرا و فضاسازی صوتی قوی، مخاطبان را به دنیای "شب‌های
    تهران" بکشاند و آن‌ها را با خود همراه سازد.</p>

<p style="text-align: justify;">مجموعه "شب‌های تهران" قرار است تا پایان سال ۱۴۰۵ به صورت هفتگی تولید و پخش شود و هر
    قسمت، داستانی تازه یا ادامه‌دهنده‌ی ماجراهای پیشین خواهد بود. این برنامه با هدف ایجاد تجربه‌ای عمیق و ماندگار برای
    شنوندگان طراحی شده است و پیش‌بینی می‌شود که به یکی از محبوب‌ترین برنامه‌های صوتی در میان مخاطبان ایرانی تبدیل شود.
</p>

<div style="background-color: #f8f9fa; padding: 15px; border-right: 4px solid #3498db; margin: 20px 0;">
    <strong>صدابازیگران:</strong> نرگس علیزادنیا، رشید فهیمی، زری راد، بوعلی همتی، یاشار علی زاده، دینا بختیاری، مریم
    پولادوند، میترا قاسملو، سایه آزاد، ریحانه حسین زاده و ...
</div>

<p style="text-align: justify;">گروه تولید رادیو سیمرغ از عموم علاقه‌مندان دعوت می‌کند تا با پیوستن به جمع شنوندگان
    "شب‌های تهران"، این تجربه صوتی نوآورانه را از دست ندهند. برای اطلاع از آخرین اخبار و قسمت‌های جدید، صفحات رسمی رادیو
    سیمرغ و پلتفرم‌های <strong>طاقچه</strong> و <strong>فیدیبو</strong> را دنبال کنید.</p>